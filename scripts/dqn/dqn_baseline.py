# CUSTOM ACHIEVEMENT TRACKER
# ================================================================
class AchievementTracker:
    """Custom tracker to ensure we capture all required achievement metrics"""
    def __init__(self):
        self.achievement_counts = {}
        self.episode_achievements = []  # Track achievements per episode
        self.all_episode_achievements = []  # Store achievements for each episode

    def reset_episode(self):
        """Reset episode-specific achievement tracking"""
        self.episode_achievements = []

    def update(self, info):
        """Update achievement counts from environment info"""
        if 'achievements' in info:
            for achievement, unlocked in info['achievements'].items():
                if unlocked and achievement not in self.episode_achievements:
                    # New achievement unlocked this episode
                    self.episode_achievements.append(achievement)
                    self.achievement_counts[achievement] = self.achievement_counts.get(achievement, 0) + 1

    def finalize_episode(self):
        """Store episode achievements and reset for next episode"""
        self.all_episode_achievements.append(self.episode_achievements.copy())
        self.reset_episode()

    def get_achievement_rates(self, total_episodes):
        """Calculate achievement unlock rates"""
        rates = {}
        for achievement, count in self.achievement_counts.items():
            rates[achievement] = count / total_episodes
        return rates

    def get_geometric_mean(self, total_episodes):
        """Calculate geometric mean of achievement unlock rates"""
        rates = list(self.get_achievement_rates(total_episodes).values())
        if not rates:
            return 0.0
        # Use maximum to avoid log(0) and minimum to avoid numerical issues
        return np.exp(np.mean(np.log(np.maximum(rates, 1e-10))))

    def get_total_unlocks(self):
        """Get total number of achievement unlocks"""
        return sum(self.achievement_counts.values())

