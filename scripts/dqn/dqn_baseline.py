class CrafterMetricsCallback(BaseCallback):
    """
    Tracks all required evaluation metrics from Section 5:
    - Achievement unlock rates
    - Geometric mean of achievement unlock rates
    - Survival time
    - Cumulative reward
    """
    def __init__(self, verbose=1):
        super().__init__(verbose)
        self.episode_rewards = []
        self.survival_times = []
        self.episode_count = 0
        self.start_time = time.time()
        self.achievement_tracker = AchievementTracker()
        self.current_episode_start = time.time()

    def _on_step(self) -> bool:
        infos = self.locals.get("infos", [])
        for info in infos:
            # Track achievements from EVERY step (not just episode ends)
            self.achievement_tracker.update(info)

            # Track episode rewards and survival times from SB3 Monitor
            if "episode" in info:
                episode_info = info["episode"]
                self.episode_rewards.append(episode_info["r"])
                self.survival_times.append(episode_info["l"])
                self.episode_count += 1

                # Finalize achievement tracking for this episode
                self.achievement_tracker.finalize_episode()

                # Progress reporting every 10 episodes
                if self.episode_count % 10 == 0:
                    recent_rewards = self.episode_rewards[-10:] if len(self.episode_rewards) >= 10 else self.episode_rewards
                    recent_survival = self.survival_times[-10:] if len(self.survival_times) >= 10 else self.survival_times
                    avg_reward = np.mean(recent_rewards)
                    avg_survival = np.mean(recent_survival)
                    elapsed_time = time.time() - self.start_time

                    # Also show achievement progress
                    total_unlocks = self.achievement_tracker.get_total_unlocks()
                    print(f"Episode {self.episode_count}: Avg Reward = {avg_reward:.2f}, Avg Survival = {avg_survival:.1f}, Achievements = {total_unlocks}, Time = {elapsed_time:.1f}s")

        return True

    def _on_training_end(self) -> None:
        """Generate final report with all required metrics from Section 5"""
        print("\n" + "="*60)
        print("EVALUATION 1: BASELINE DQN - FINAL RESULTS")
        print("="*60)

        if self.episode_count > 0:
            # Required metrics from Section 5
            avg_reward = np.mean(self.episode_rewards)
            avg_survival = np.mean(self.survival_times)
            reward_std = np.std(self.episode_rewards)
            max_reward = np.max(self.episode_rewards)
            max_survival = np.max(self.survival_times)

            print(f"Total Episodes: {self.episode_count}")
            print(f"Average Cumulative Reward: {avg_reward:.2f} ± {reward_std:.2f}")
            print(f"Average Survival Time: {avg_survival:.1f} steps")
            print(f"Max Reward: {max_reward:.2f}")
            print(f"Longest Survival: {max_survival} steps")

            # Analyze achievement data using our custom tracker
            self._analyze_achievements()

        total_time = time.time() - self.start_time
        print(f"\nTotal Training Time: {total_time:.1f} seconds")
        print(f"Logs saved to: {RESULTS_DIR}")
        print("✅ Evaluation 1 (Baseline DQN) complete.")

    def _analyze_achievements(self):
        """Analyze achievement unlock rates using our custom tracker"""
        print("\n--- ACHIEVEMENT UNLOCK RATES (Section 5 Metric) ---")

        # Get achievement rates from our custom tracker
        achievement_rates = self.achievement_tracker.get_achievement_rates(self.episode_count)
        rates = []
        total_unlocks = self.achievement_tracker.get_total_unlocks()

        if achievement_rates:
            for achievement, rate in sorted(achievement_rates.items()):
                count = int(rate * self.episode_count)
                rates.append(rate)
                print(f"  {achievement}: {rate:.1%} ({count}/{self.episode_count})")

            # Geometric mean of achievement unlock rates (required metric)
            geom_mean = self.achievement_tracker.get_geometric_mean(self.episode_count)
            print(f"\nGeometric Mean of Achievement Unlock Rates: {geom_mean:.4f}")
            print(f"Total Achievement Unlocks: {total_unlocks}")

            # Also check built-in logging for comparison
            self._check_builtin_achievements()
        else:
            print("No achievements recorded during training")
            self._check_builtin_achievements()

    def _check_builtin_achievements(self):
        """Check if built-in Crafter logging also captured achievements"""
        try:
            stats_file = f"{RESULTS_DIR}/baseline_dqn.json"

            if os.path.exists(stats_file):
                with open(stats_file, 'r') as f:
                    stats = json.load(f)

                if 'achievements' in stats:
                    print("\n--- BUILT-IN ACHIEVEMENT LOGGING ---")
                    achievements = stats['achievements']
                    builtin_total = sum(achievements.values())
                    print(f"Built-in logger recorded {builtin_total} achievement unlocks")
                    if builtin_total != self.achievement_tracker.get_total_unlocks():
                        print("⚠️  Custom tracker and built-in logger have different counts!")
        except Exception as e:
            print(f"Note: Built-in achievement check failed: {e}")

